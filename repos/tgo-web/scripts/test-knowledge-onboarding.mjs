import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';

const source = fs.readFileSync('src/utils/knowledgeOnboarding.ts', 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { getKnowledgeUseState: state, createKnowledgeTextFile } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const file = { processing_status: 'completed', statusType: 'success', document_count: 3 };
const record = { review_status: 'approved', allow_automatic_reply: true, source_origin: 'internal', effective_at: '2026-01-01T00:00:00Z', expires_at: null, channels: ['wecom_kf'] };
const now = Date.parse('2026-10-20T00:00:00Z');
assert.equal(state(file, record, true, now), 'authorized');
assert.equal(state({ ...file, processing_status: 'pending' }, record, true, now), 'parsing');
assert.equal(state({ ...file, processing_status: 'failed' }, record, true, now), 'failed');
assert.equal(state({ ...file, document_count: 0 }, record, true, now), 'empty');
assert.equal(state(file, record, false, now), 'unknown');
assert.equal(state(file, undefined, true, now), 'unconfigured');
for (const status of ['draft', 'pending_review', 'rejected', 'revoked']) assert.equal(state(file, { ...record, review_status: status }, true, now), status);
assert.equal(state(file, { ...record, allow_automatic_reply: false }, true, now), 'disabled');
assert.equal(state(file, { ...record, source_origin: 'customer' }, true, now), 'untrusted');
assert.equal(state(file, { ...record, effective_at: '2027-01-01T00:00:00Z' }, true, now), 'scheduled');
assert.equal(state(file, { ...record, expires_at: '2026-10-20T00:00:00Z' }, true, now), 'expired');
assert.equal(state(file, { ...record, effective_at: 'bad date' }, true, now), 'unknown');
assert.equal(state(file, { ...record, channels: [] }, true, now), 'no_channel');
const body = '  # 企业资料\n\n中文正文，不能放在简介里。\r\n结尾空格  \n';
const upload = createKnowledgeTextFile('产品/介绍', body);
assert.equal(await upload.text(), body);
assert.equal(upload.name, '产品_介绍.md');
assert.equal(upload.size, Buffer.byteLength(body));
assert.throws(() => createKnowledgeTextFile('空白', '\n  '));
console.log('knowledge onboarding: 19 eligibility and exact-content assertions passed');
